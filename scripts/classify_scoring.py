    scores = compute_subject_scores(text, options, explanation)
    best_subj = max(scores, key=scores.get)
    max_score = scores[best_subj]
    
    # If the top score is strong (>= 12), use it with certainty
    if max_score >= 12:
        return best_subj
    
    # If score is modest (e.g. 5 to 11), only switch if fallback was clearly something else
    # Otherwise keep fallback
    return fallback_subject
