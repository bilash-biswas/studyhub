const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function formatNumberByLang(value: number | string, lang: "bn" | "en"): string {
  const num = typeof value === "number" ? value.toLocaleString("en-IN") : String(value);
  if (lang === "en") return num;
  return num.replace(/\d/g, (d) => BN_DIGITS[Number(d)] || d);
}
